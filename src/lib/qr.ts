/**
 * A small, dependency-free QR Code encoder (byte mode, versions 1–40).
 * Runs entirely in the browser, so the Access Passport never touches a server.
 * Follows ISO/IEC 18004; structure adapted from Project Nayuki's reference
 * implementation (MIT).
 */

export type QrEcc = "L" | "M" | "Q" | "H";

const ECC_ORDINAL: Record<QrEcc, number> = { L: 0, M: 1, Q: 2, H: 3 };
const ECC_FORMAT_BITS = [1, 0, 3, 2];

